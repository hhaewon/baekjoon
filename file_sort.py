SOLVED_DIR = "solved"
UNSOLVED_DIR = "unsolved"

os.makedirs(SOLVED_DIR, exist_ok=True)
os.makedirs(UNSOLVED_DIR, exist_ok=True)

def safe_remove(path):
    """Windows에서도 권한 문제 없이 삭제"""
    try:
        os.remove(path)
    except PermissionError:
        # 읽기 전용 속성 제거 후 재시도
        os.chmod(path, stat.S_IWRITE)
        os.remove(path)

def clean_and_sort(folder):
    for filename in os.listdir(folder):
        path = os.path.join(folder, filename)

        if os.path.isdir(path):
            clean_and_sort(path)
            continue

        # exe 또는 확장자 없는 파일 무조건 삭제
        if filename.endswith(".exe") or "." not in filename:
            print(f"삭제: {path}")
            safe_remove(path)
            continue

        # 숫자로 시작하는 파일만 문제 코드로 인정
        match = re.match(r"^(\d+)", filename)
        if not match:
            print(f"삭제(이상한 파일): {path}")
            safe_remove(path)
            continue

        problem_num = int(match.group(1))

        # 목적지 판단
        if problem_num in solved_set:
            dest_dir = SOLVED_DIR
        else:
            dest_dir = UNSOLVED_DIR

        dest = os.path.join(dest_dir, filename)

        # 이미 제자리에 있으면 스킵
        if os.path.abspath(os.path.dirname(path)) == os.path.abspath(dest_dir):
            continue

        print(f"{path} → {dest}")
        shutil.move(path, dest)

# 실행
clean_and_sort(SOLVED_DIR)
clean_and_sort(UNSOLVED_DIR)
